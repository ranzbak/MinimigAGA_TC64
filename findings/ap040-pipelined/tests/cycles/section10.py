def lead_base(e):
    m = re.fullmatch(r"(?:(\d+)L\+)?(\d+)", e)
    return (int(m.group(1) or 0), int(m.group(2)))

def cycles(cell):
    """cell 'calc/exec[/alt...]' -> (calc, exec_text, cycles).  Alternatives:
    'c/e1/e2' (T1/T2 exec), 'c1/c2/e1/e2' (T1/T2 calc and exec), 'c1/c2/e' ."""
    parts = cell.split("/")
    if len(parts) == 2:
        c, e = parts
    elif len(parts) == 3:
        # 'c/e1/e2' (exec alternatives) -- the only 3-part shape in the tables
        c, e = parts[0], parts[1]
    else:
        c, e = parts[0], parts[2]
    L, B = lead_base(e)
    return int(c), e, max(int(c), L + B)

def rows():
    out = []
    for (ins, page), cells in T.items():
        for m, cell in zip(MODES, cells):
            if cell == "-":
                continue
            c, e, n = cycles(cell)
            out.append((ins, m, "", c, e, n, page))
    for s in MOVE_SRC:
        for d, cell in zip(MOVE_DST, MOVE[s].split()):
            c, e, n = cycles(cell)
            out.append(("MOVE", s, d, c, e, n, "10-9/10-10"))
    for ins, cond, cell in MISC:
        c, e, n = cycles(cell)
        out.append((ins, cond, "", c, e, n, "10-11/10-12"))
    return out

