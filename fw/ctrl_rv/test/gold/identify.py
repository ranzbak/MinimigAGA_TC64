#!/usr/bin/env python3
"""identify.py <dir>: the IDENTIFY DEVICE data the 832 sends, for hdd_test (Task 12).

ATA_IdentifyDevice sends the 256 words of IDENTIFY DEVICE through the Gayle
FIFO (CMD_IDE_DATA_WR), each word low byte first.  The bytes of that stream
(512, after the frame's 6 command bytes) are built here from:

  - ATA (ATA-1 / ATA-2, IDENTIFY DEVICE): every word goes low byte first;
    the strings (serial number words 10-19, firmware revision 23-26, model
    number 27-46) hold two characters per word, the FIRST character in bits
    15:8.  So a string reaches the wire as its characters pairwise
    exchanged: "1234" -> '2' '1' '4' '3'.
  - the 832's observable stream: on the big-endian 832, IdentifyDevice's
    memcpy of a string into the word array puts character 2k in bits 15:8
    of word k -- exactly ATA's order -- and the low-byte-first send then
    gives the pairwise exchange above.  (On a little-endian CPU the same
    memcpy puts it in bits 7:0, hence the 16-bit swap of the RISC-V port.)
  - the values the 832 firmware puts in the words (not taken from
    fw/ctrl_rv/hdd.c's code, stated here): word 0 0x0040 (fixed disk),
    1 cylinders, 3 heads, 6 sectors per track, 47 0x8010 (READ/WRITE
    MULTIPLE, at most 16 sectors), 53 1 (words 54-58 valid), 54-56 the
    current cylinders, heads, sectors, 57-58 cylinders*heads*sectors (32
    bits, low word first); every other word 0.
    Strings of a hardfile (HDF_FILE, HDF_FILE | HDF_SYNTHRDB):
      serial "1234567890ABCDEFGHIJ", firmware ".100    ",
      model: SYNTHRDB "DON'T   REPARTITION!" and spaces; otherwise
      "YAQUBE  " then the config's long name (up to 16 characters, up to
      its first NUL) or, when that is empty, its 8-character name, then
      spaces (40 characters in all).
    Strings of the SD card (HDF_CARD, HDF_CARDPART0..3): serial
    "TC64MiniMigSD0      ", firmware ".100    ", model "YAQUBE  " then
    "SD/MMC Card" (whole card) or "Card Part n" (n = partition + 1), spaces.

Written into <dir>/identcases.h: ident_<i>[512] (the stream of each case)
and IDENT_CASES, the table hdd_test runs ({what, type, partition, cylinders,
heads, sectors, name[8], long_name[16], stream}).  python3 -I, standard
library only.
"""
import os
import sys

HDF_FILE, HDF_CARD, HDF_CARDPART0, HDF_SYNTHRDB = 1, 2, 3, 128

# what, type, partition, cylinders, heads, sectors, name (8), long name (<= 16)
CASES = [
    ("WORK.HDF long name", HDF_FILE, 0, 32, 4, 63, b"WORK    ", b"WORK"),
    ("WORK.HDF 8.3 name", HDF_FILE, 0, 32, 4, 63, b"WORK    ", b""),
    ("WORK.HDF SYNTHRDB", HDF_FILE | HDF_SYNTHRDB, 0, 129, 1, 32, b"WORK    ", b"WORK"),
    ("WORK.HDF SYNTHRDB 8.3", HDF_FILE | HDF_SYNTHRDB, 0, 129, 1, 32, b"WORK    ", b""),
    ("odd-length long name", HDF_FILE, 0, 80, 4, 63, b"WORKS   ", b"WORKS"),
    ("16-character long name", HDF_FILE, 0, 1023, 16, 63, b"WORKBE~1", b"Workbench 3.1 HD"),
    ("2 GB SYNTHRDB", HDF_FILE | HDF_SYNTHRDB, 0, 32769, 4, 32, b"BIG     ", b"Big"),
    ("SD card", HDF_CARD, 0, 1000, 16, 63, b"\0" * 8, b""),
    ("SD card partition 3", HDF_CARDPART0 + 2, 2, 980, 16, 63, b"\0" * 8, b""),
]


def strings(typ, part, name, long_name):
    if typ & 15 == HDF_FILE:
        serial = b"1234567890ABCDEFGHIJ"
        if typ & HDF_SYNTHRDB:
            model = b"DON'T   REPARTITION!"
        else:
            model = b"YAQUBE  " + (long_name[:16] if long_name else name[:8])
    else:
        serial = b"TC64MiniMigSD0      "
        if typ == HDF_CARD:
            model = b"YAQUBE  SD/MMC Card"
        else:
            model = b"YAQUBE  Card Part " + bytes((ord("1") + part,))
    return serial, b".100    ", model.ljust(40, b" ")


def stream(typ, part, cyl, heads, secs, name, long_name):
    w = [0] * 256
    w[0] = 0x0040
    w[1], w[3], w[6] = cyl, heads, secs
    serial, fw, model = strings(typ, part, name, long_name)
    for first, s in ((10, serial), (23, fw), (27, model)):
        for k in range(len(s) // 2):
            w[first + k] = s[2 * k] << 8 | s[2 * k + 1]   # first character in bits 15:8
    w[47] = 0x8010
    w[53] = 1
    w[54], w[55], w[56] = cyl, heads, secs
    total = cyl * heads * secs
    w[57], w[58] = total & 0xFFFF, total >> 16 & 0xFFFF
    return bytes(b for v in w for b in (v & 0xFF, v >> 8))   # low byte first


def hexbytes(b):
    return "{" + ", ".join("0x%02x" % x for x in b) + "}"


def main():
    if len(sys.argv) != 2:
        raise SystemExit("usage: identify.py <dir>")
    d = sys.argv[1]
    os.makedirs(d, exist_ok=True)
    out = ["/* generated by gold/identify.py: IDENTIFY DEVICE as the 832 sends it */\n"]
    rows = []
    for i, (what, typ, part, cyl, heads, secs, name, long_name) in enumerate(CASES):
        s = stream(typ, part, cyl, heads, secs, name, long_name)
        out.append("static const unsigned char ident_%d[512] = {\n" % i)
        for j in range(0, 512, 16):
            out.append("\t" + ", ".join("0x%02x" % x for x in s[j:j + 16]) + ",\n")
        out.append("};\n")
        rows.append('\t{ "%s", %d, %d, %d, %d, %d, %s, %s, ident_%d },\n'
                    % (what, typ, part, cyl, heads, secs, hexbytes(name.ljust(8, b"\0")),
                       hexbytes(long_name.ljust(16, b"\0")), i))
    out.append("#define IDENT_CASES \\\n")
    out.append("".join(r.rstrip("\n") + " \\\n" for r in rows))
    out.append("\n")
    with open(os.path.join(d, "identcases.h"), "w") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
