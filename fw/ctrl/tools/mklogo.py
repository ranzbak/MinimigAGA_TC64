#!/usr/bin/env python3
"""The Minimig logo as glyphs of the OSD text layer (findings/osd-redesign/plan.md 3.9).

    mklogo.py [--logo fw/ctrl/logo.h] [--out fw/ctrl/osd_logo.h]
        osd_logo.h from logo.h.  --check: compare with the existing file
        instead of writing it (exit 1 on a difference; make check (k)).

logo.h is the legacy OSD's bitmap: 5 strips x 227 columns, each byte one
pixel COLUMN of its 8-pixel strip, bit 0 = top (40 x 227 pixels).  Its ink
fills x 3..226, y 5..36: exactly 224 x 32 pixels, 28 x 2 glyphs of 8 x 16.
osd_logo.h holds the distinct glyphs (row-major, bit 7 = left pixel, the
font's format) and the 28 x 2 map of glyph indices; at scale 2 the logo is
448 x 64 pixels.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEF_LOGO = os.path.normpath(os.path.join(HERE, "..", "logo.h"))
DEF_OUT = os.path.normpath(os.path.join(HERE, "..", "osd_logo.h"))

STRIPS, WIDTH = 5, 227
X0, Y0, COLS, ROWS = 3, 5, 28, 2


def pixels(path):
    with open(path) as f:
        text = f.read()
    body = text[text.index("{"):]
    nums = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body)]
    if len(nums) != STRIPS * WIDTH:
        sys.exit("%s: %d bytes, want %d" % (path, len(nums), STRIPS * WIDTH))
    px = [[0] * WIDTH for _ in range(STRIPS * 8)]
    for s in range(STRIPS):
        for x in range(WIDTH):
            b = nums[s * WIDTH + x]
            for k in range(8):
                px[s * 8 + k][x] = (b >> k) & 1
    # the crop must hold all the ink
    for y in range(STRIPS * 8):
        for x in range(WIDTH):
            if px[y][x] and not (X0 <= x < X0 + 8 * COLS and Y0 <= y < Y0 + 16 * ROWS):
                sys.exit("%s: ink at (%d, %d) outside the crop" % (path, x, y))
    return px


def render(px):
    glyphs, index, cmap = [], {}, []
    for gr in range(ROWS):
        line = []
        for gc in range(COLS):
            g = tuple(sum(px[Y0 + gr * 16 + r][X0 + gc * 8 + b] << (7 - b) for b in range(8))
                      for r in range(16))
            if g not in index:
                index[g] = len(glyphs)
                glyphs.append(g)
            line.append(index[g])
        cmap.append(line)
    out = []
    out.append("/* osd_logo.h: the Minimig logo (logo.h) as 8x16 glyphs of the OSD text")
    out.append(" * layer, %d x %d cells (448 x 64 pixels at scale 2).  Generated by" % (COLS, ROWS))
    out.append(" * fw/ctrl/tools/mklogo.py from logo.h: do not edit (make check (k)). */")
    out.append("#ifndef OSD_LOGO_H")
    out.append("#define OSD_LOGO_H")
    out.append("")
    out.append("#define OSD_LOGO_COLS   %d" % COLS)
    out.append("#define OSD_LOGO_ROWS   %d" % ROWS)
    out.append("#define OSD_LOGO_GLYPHS %d" % len(glyphs))
    out.append("")
    out.append("/* the distinct glyphs: 16 rows, bit 7 = the left pixel */")
    out.append("static const unsigned char osd_logo_glyph[OSD_LOGO_GLYPHS][16] = {")
    for i, g in enumerate(glyphs):
        out.append("\t{ " + ", ".join("0x%02X" % b for b in g) + " },  /* %d */" % i)
    out.append("};")
    out.append("")
    out.append("/* the cells: the glyph of each */")
    out.append("static const unsigned char osd_logo_map[OSD_LOGO_ROWS][OSD_LOGO_COLS] = {")
    for line in cmap:
        out.append("\t{ " + ", ".join("%2d" % v for v in line) + " },")
    out.append("};")
    out.append("")
    out.append("#endif")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--logo", default=DEF_LOGO)
    ap.add_argument("--out", default=DEF_OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(pixels(a.logo))
    if a.check:
        try:
            with open(a.out) as f:
                have = f.read()
        except OSError:
            have = None
        if have != text:
            print("%s is not mklogo.py's output of %s" % (a.out, a.logo))
            return 1
        return 0
    with open(a.out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
